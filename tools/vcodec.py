"""Video encoder of the demo (docs/format.md), reference decoder and cycle model. Standard library only.

The picture is 256x192, 1 bit per pixel (logical: 1 = white), shown on CGA-1V in CGA mode (2 bits per pixel,
white = both bits), centred: row y at offset (y + 4) * 80 + 8 of the page. A picture row is a Python int,
bit x = pixel x.

Double buffering: the CPU page holds the picture of frame n-2. Frame n is coded as XOR intervals between that
picture and the new one, grouped into vertical tracks (tools/vfmt.py). The decoder (generated by
tools/mkvdec.py) costs about 80 T per row of a track inside one byte.

Time: the demo shows a frame at a VBI (59.94 Hz). The decoder starts frame n when frame n-1 is shown; frame n
is due 2 VBIs later. The encoder simulates that with the cycle model and takes for every frame the source
frame of its real display time, so a slow frame (a cut) drops the next one instead of delaying the rest.
The time the interrupt takes depends on the music: build/music.bin must be made first (tools/mkmusic.py).

Stream: per frame 1 B header (VBIs after the previous frame, 0 = end of the video), then the tracks, END.

Usage: python tools/vcodec.py [--frames N] [--out build/video.bin] [--dz 1] [--check]
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import frames  # noqa: E402
import mkvdec  # noqa: E402
import vfmt  # noqa: E402

W, H = 256, 192
FULL = (1 << W) - 1
THR = bytes((b'1' if v >= 128 else b'0')[0] for v in range(256))
TOP = 4                       # picture rows start at line 4
LEFT = 8                      # and byte 8 of the line
PAGE = 0x4000

# cycle model: T at 4 MHz incl. the waits of CGA-1V measured on the real HW (per access)
CGA_R, CGA_W = 1.26, 2.43
VBI_T = 66_733                # 4 MHz / 59.94 Hz
# The interrupt (sapi/badapple.asm isr, 1300.7 Hz) takes from every VBI: 21.7 calls of 183 T with nothing to do,
# the VBI itself (~300 T), the tick of the music (~250 T) and 168 T more for each register write of the music.
# The writes per VBI come from build/music.bin (tools/mkmusic.py; tick k plays at VBI k), the most of the VBI and
# its neighbours (the player follows the video within a tick or so).
ISR_BASE_T = 4_550
ISR_WRITE_T = 168
MUSIC = os.path.join(ROOT, 'build', 'music.bin')
FRAME_T = 4_000               # per frame: main loop, frame start, the flip seen up to one interrupt late
T_READ = 16                   # reading the stream from the RAM disk, per byte (unrolled INI)
MX_MID_T = 37                 # each further middle byte of an MX row


def rows_of(data, i):
    f = data[i * W * H:(i + 1) * W * H].translate(THR)
    return [int(f[y * W:(y + 1) * W][::-1], 2) for y in range(H)]


def runs(d):
    """Runs of ones in d: list of (s, e1) (e1 inclusive), ascending."""
    s = d & ~(d << 1)
    e = ~d & (d << 1)
    out = []
    while s:
        lo = s & -s
        a = lo.bit_length() - 1
        rest = e >> a
        out.append((a, a + (rest & -rest).bit_length() - 2))
        s ^= lo
    return out


def deadzone(d, dz, new=None):
    """Drop runs of at most dz pixels from the change d when they lie next to an edge of the new row (the
    edge only jitters); other runs (a dot that came or went) stay."""
    if dz <= 0 or not d:
        return d
    edges = None if new is None else new ^ (new << 1)          # bit x: pixel x differs from pixel x-1
    for a, b in runs(d):
        if b - a < dz:
            if edges is not None and not ((edges >> a) & 1 or (edges >> (b + 1)) & 1):
                continue
            d &= ~(((1 << (b - a + 1)) - 1) << a)
    return d


def row_addr(y):
    return (y + TOP) * vfmt.ROW + LEFT


# --- video memory rendering ------------------------------------------------------------------------------
REV4 = [int(f'{v:04b}'[::-1], 2) for v in range(16)]
NIB2BYTE = bytes(REV4[v] * 0x11 for v in range(16))


def render_row(r):
    """Picture row int -> 64 B of CGA mode."""
    return bytes(NIB2BYTE[(r >> (4 * j)) & 15] for j in range(64))


def render(rows):
    page = bytearray(PAGE)
    for y, r in enumerate(rows):
        a = row_addr(y)
        page[a:a + 64] = render_row(r)
    return page


# --- tracks ----------------------------------------------------------------------------------------------
def op_cost(code):
    t, r, w = mkvdec.costs()[code[0]]
    if vfmt.OPS[code[0]][0] == 'MX':
        m = vfmt.mx_m(code[1])
        t += m * mkvdec.MX_FILL[0] + mkvdec.MX_TAIL[0]
        r += m * mkvdec.MX_FILL[1] + mkvdec.MX_TAIL[1]
        w += m * mkvdec.MX_FILL[2] + mkvdec.MX_TAIL[2]
    return t + r * CGA_R + w * CGA_W


def nib(row, j):
    """Pixels of byte j of a row (4 bits, bit 0 = pixel 4j)."""
    return (row >> (4 * j)) & 15


def split_middles(ivs, old):
    """Intervals with 3 or more middle bytes are filled (MX): split those whose middle bytes are not all of one
    colour in the old row into pieces of at most 4 bytes (M codes, XOR)."""
    out = []
    for s, e1 in ivs:
        bs, be = s >> 2, e1 >> 2
        if be - bs - 1 >= 3:
            mids = {nib(old, j) for j in range(bs + 1, be)}
            if len(mids) > 1 or mids - {0, 15}:
                x = s
                while x <= e1:
                    end = min(e1, ((x >> 2) + 4) * 4 - 1)
                    out.append((x, end))
                    x = end + 1
                continue
        out.append((s, e1))
    return out


def build_tracks(ivrows):
    """ivrows: per row the list of (s, e1). Link intervals of consecutive rows whose left byte moves by at most
    one byte; returns a list of tracks, each (y0, [(s, e1), ...])."""
    tracks = []
    open_ = []                          # (left byte, track index) of the previous row
    for y in range(H):
        cur = []
        used = set()
        for s, e1 in ivrows[y]:
            bs = s >> 2
            best = None
            for k, (pbs, ti) in enumerate(open_):
                if k in used:
                    continue
                dd = abs(bs - pbs)
                if dd <= 1 and (best is None or dd < best[0]):
                    best = (dd, k)
                    if dd == 0:
                        break
            if best is None:
                tracks.append((y, [(s, e1)]))
                ti = len(tracks) - 1
            else:
                used.add(best[1])
                ti = open_[best[1]][1]
                tracks[ti][1].append((s, e1))
            cur.append((bs, ti))
        open_ = cur
    return tracks


T_CLR_OP = 222 + 10          # CLR: handler jump, parameters, DI, SP, dispatch
T_CLR_ROW = 413 + 64 * CGA_W  # per row: 32 x PUSH, EI window


def clr_cost(rows):
    return T_CLR_OP + rows * T_CLR_ROW


def encode_tracks(tracks, base, out, cyc=0):
    """Append the tracks and END to out; base = old rows (after clears) for the colour of MX; returns cycles."""
    tstart = None
    for y0, ivs in sorted(tracks, key=lambda t: row_addr(t[0]) + (t[1][0][0] >> 2)):
        de = 0xC000 + row_addr(y0) + (ivs[0][0] >> 2) - vfmt.ROW
        if tstart is not None and 0 <= de - tstart <= 255:
            code = bytes([vfmt.OP_TRACKR, de - tstart])
        else:
            code = bytes([vfmt.OP_TRACKA, de & 0xFF, de >> 8])
        tstart = de
        out += code
        cyc += op_cost(code)
        prev = ivs[0][0] >> 2
        for k, (s, e1) in enumerate(ivs):
            fill = 0xFF if nib(base[y0 + k], (s >> 2) + 1) == 0 else 0
            code = vfmt.code_for((s >> 2) - prev, s, e1, fill)
            prev = s >> 2
            out += code
            cyc += op_cost(code)
    out.append(vfmt.OP_END)
    cyc += op_cost(bytes([vfmt.OP_END]))
    return cyc


def iv_cost(ivs):
    """Rough cost of intervals (for choosing between XOR and clearing a row)."""
    c = 0
    for s, e1 in ivs:
        m = (e1 >> 2) - (s >> 2) - 1
        c += 95 if m < 0 else (135 + 28 * m if m < 3 else 200 + 16 * m)
    return c


# --- reference decoder (byte exact, like the Z80 code) ---------------------------------------------------
def decode_frame(buf, pos, page):
    """Apply the frame body at buf[pos:] to page (bytearray of 16 KB, offset 0 = C000h); returns the new pos."""
    de = 0
    tstart = 0
    while True:
        op = vfmt.OPS[buf[pos]]
        pos += 1
        k = op[0]
        if k == 'END':
            return pos
        if k == 'TRACKA':
            de = tstart = buf[pos] | buf[pos + 1] << 8
            pos += 2
            continue
        if k == 'TRACKR':
            de = tstart = (tstart + buf[pos]) & 0xFFFF
            pos += 1
            continue
        if k == 'CLR':
            a = (buf[pos] | buf[pos + 1] << 8) - 0xC000
            rows, col = buf[pos + 2], buf[pos + 3]
            pos += 4
            for r in range(rows):
                page[a + r * vfmt.ROW:a + r * vfmt.ROW + 64] = bytes([col]) * 64
            continue
        de = (de + vfmt.ROW + op[1]) & 0xFFFF
        a = de - 0xC000
        if k == 'S':
            page[a] ^= vfmt.pix_mask(op[2], op[3])
            continue
        page[a] ^= vfmt.pix_mask(op[2], 3)
        if k == 'M':
            m = op[4]
            for i in range(1, m + 1):
                page[a + i] ^= 0xFF
        else:
            m = vfmt.mx_m(buf[pos])
            col = 0xFF if buf[pos] & 1 else 0
            pos += 1
            page[a + 1:a + m + 1] = bytes([col]) * m
        page[a + m + 1] ^= vfmt.pix_mask(0, op[3])


# --- encoder ---------------------------------------------------------------------------------------------
def frame_body(page_rows, new_rows, use_clr=True):
    """Body of one frame: CLR of rows where clearing and drawing the new row is cheaper than XOR, tracks, END.
    Returns (bytes, cycles)."""
    ivrows = []
    base = []                                  # old rows after the clears
    clr = []                                   # per row: None or colour 0 / 1
    for y in range(H):
        iv = split_middles(runs(page_rows[y] ^ new_rows[y]), page_rows[y])
        best = (iv_cost(iv), None, iv, page_rows[y])
        if use_clr and best[0] > T_CLR_ROW:
            for col in (0, 1):
                b = FULL if col else 0
                iv2 = runs(new_rows[y] ^ b)
                c = T_CLR_ROW + 60 + iv_cost(iv2)
                if c < best[0]:
                    best = (c, col, iv2, b)
        clr.append(best[1])
        ivrows.append(best[2])
        base.append(best[3])
    out = bytearray()
    cyc = 0
    y = 0
    while y < H:
        if clr[y] is None:
            y += 1
            continue
        y1 = y
        while y1 + 1 < H and clr[y1 + 1] == clr[y]:
            y1 += 1
        a = 0xC000 + row_addr(y)
        out += bytes([vfmt.OP_CLR, a & 0xFF, a >> 8, y1 - y + 1, 0xFF if clr[y] else 0])
        cyc += clr_cost(y1 - y + 1)
        y = y1 + 1
    cyc = encode_tracks(build_tracks(ivrows), base, out, cyc)
    return out, cyc + len(out) * T_READ


def music_writes(path=MUSIC):
    """Register writes of the music per tick (empty without build/music.bin)."""
    if not os.path.exists(path):
        return []
    st = open(path, 'rb').read()
    p = 0
    while st[p] < 0xFE:
        p += 2
    out = []
    while st[p] != 0xFE:
        if st[p] == 0xFF:
            out.append(0)
            p += 1
        else:
            out[-1] += 1
            p += 2
    return out


MUSIC_WRITES = music_writes()


def free_t(v):
    """T of the decoder in VBI v (the interrupt and the music taken away)."""
    w = max(MUSIC_WRITES[max(0, v - 1):v + 2] or [0])
    return VBI_T - ISR_BASE_T - ISR_WRITE_T * w


def vbis_needed(cyc, start):
    """VBIs a frame of cyc T of the decoder takes from VBI start on (at least 2: 29.97 fps)."""
    need, have = 0, 0
    while have < cyc + FRAME_T or need < 2:
        have += free_t(start + need)
        need += 1
    return need


def encode(n_frames=None, dz=1, dz_max=3, check=False, verbose=True):
    n_src, data = frames.load(W, H)
    t_end = (frames.SRC_FRAMES * 1001 // 1000) * 2      # VBIs of the whole video
    pages = [[0] * H, [0] * H]
    vram = [bytearray(PAGE), bytearray(PAGE)]
    shown = [0] * H
    stream = bytearray()
    stats = []
    flip = -2                     # VBI of the flip of the previous frame
    n = 0
    while True:
        target = flip + 2
        if target >= t_end or (n_frames and n >= n_frames):
            break
        page = pages[n & 1]
        src = min(frames.SRC_FRAMES - 1, round(target * 1001 / 2000))
        img = rows_of(data, src)
        for z in range(dz, dz_max + 1):
            new = [shown[y] ^ deadzone(shown[y] ^ img[y], z, img[y]) for y in range(H)]
            body, cyc = frame_body(page, new)
            need = vbis_needed(cyc, flip)
            if need <= 2:
                break
        if need > 2:
            # too slow (a cut): show it later and take the source frame of that time
            target = flip + need
            src = min(frames.SRC_FRAMES - 1, round(target * 1001 / 2000))
            img = rows_of(data, src)
            new = [shown[y] ^ deadzone(shown[y] ^ img[y], dz_max, img[y]) for y in range(H)]
            body, cyc = frame_body(page, new)
            need = vbis_needed(cyc, flip)
            target = max(target, flip + need)
        if check:
            v = vram[n & 1]
            decode_frame(body, 0, v)
            assert v == render(new), f'frame {n}: decoder mismatch'
        stream += bytes([target - flip]) + body
        pages[n & 1] = new
        shown = new
        err = sum(bin(new[y] ^ img[y]).count('1') for y in range(H))
        stats.append((len(body) + 1, cyc, z, err, target - flip))
        flip = target
        n += 1
        if verbose and n % 1000 == 0:
            print(f'  frame {n}: {len(stream)} B', flush=True)
    stream.append(0)
    return stream, stats


def report(stats):
    m = len(stats)

    def q(col):
        v = sorted(s[col] for s in stats)
        return (f'median {v[m // 2]:.0f} p90 {v[m * 9 // 10]:.0f} p99 {v[m * 99 // 100]:.0f} '
                f'max {v[-1]:.0f} mean {sum(v) / m:.0f}')
    print(f'frames {m}, total {sum(s[0] for s in stats) / 1e6:.3f} MB')
    print('  bytes/frame ', q(0))
    print('  T/frame     ', q(1))
    print('  wrong px    ', q(3))
    for z in range(1, 9):
        c = sum(1 for s in stats if s[2] == z)
        if c:
            print(f'    dz {z}: {c} frames ({100 * c / m:.1f} %)')
    for v in range(2, 16):
        c = sum(1 for s in stats if s[4] == v)
        if c:
            print(f'    {v} VBIs: {c} frames')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--frames', type=int)
    ap.add_argument('--dz', type=int, default=1)
    ap.add_argument('--dzmax', type=int, default=3)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--out')
    a = ap.parse_args()
    stream, stats = encode(a.frames, a.dz, a.dzmax, a.check)
    report(stats)
    if a.out:
        os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
        open(a.out, 'wb').write(stream)
        print(f'{a.out}: {len(stream)} B')


if __name__ == '__main__':
    main()
