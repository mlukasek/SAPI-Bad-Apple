"""Video encoder of the demo (docs/format.md), reference decoder and cycle model. Standard library only.

The picture is 256x192, 1 bit per pixel (logical: 1 = white), shown on CGA-1V in CGA mode (2 bits per pixel,
white = both bits), centred: row y at offset (y + 4) * 80 + 8 of the page. A picture row is a Python int,
bit x = pixel x.

Double buffering: the CPU page holds the picture of frame n-2. Frame n is coded as XOR intervals between that
picture and the new one, grouped into vertical tracks (tools/vfmt.py). The decoder (generated by
tools/mkvdec.py) costs about 80 T per row of a track inside one byte.

Time: the demo shows a frame at a VBI (59.94 Hz). The decoder starts frame n when frame n-1 is shown; frame n
is due 2 VBIs later. The encoder simulates that with the cycle model and takes for every frame the source
frame of its real display time, so a slow frame (a cut) drops the next one instead of delaying the rest.
The time the interrupt takes depends on the music: build/music.bin must be made first (tools/mkmusic.py).

Stream: per frame 1 B header (VBIs after the previous frame, 0 = end of the video), then the tracks, END.

Usage: python tools/vcodec.py [--frames N] [--out build/video.bin] [--check]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import frames  # noqa: E402
import mkvdec  # noqa: E402
import vfmt  # noqa: E402

W, H = 256, 192
FULL = (1 << W) - 1
THR = bytes((b'1' if v >= 128 else b'0')[0] for v in range(256))
TOP = 4                       # picture rows start at line 4
LEFT = 8                      # and byte 8 of the line
PAGE = 0x4000

# cycle model: T at 4 MHz incl. the waits of CGA-1V measured on the real HW (per access)
CGA_R, CGA_W = 1.26, 2.43
VBI_T = 66_733                # 4 MHz / 59.94 Hz
# The interrupt (sapi/badapple.asm isr, 1300.7 Hz) takes from every VBI: 21.7 calls of 183 T with nothing to do,
# the VBI itself (~300 T), the tick of the music (~250 T) and 168 T more for each register write of the music.
# The writes per VBI come from build/music.bin (tools/mkmusic.py; tick k plays at VBI k), the most of the VBI and
# its neighbours (the player follows the video within a tick or so).
ISR_BASE_T = 4_550
ISR_WRITE_T = 168
MUSIC = os.path.join(ROOT, 'build', 'music.bin')
FRAME_T = 4_000               # per frame: main loop, frame start, the flip seen up to one interrupt late
T_READ = 16                   # reading the stream from the RAM disk, per byte (unrolled INI)
MX_MID_T = 37                 # each further middle byte of an MX row


def rows_of(data, i):
    f = data[i * W * H:(i + 1) * W * H].translate(THR)
    return [int(f[y * W:(y + 1) * W][::-1], 2) for y in range(H)]


# Stars: the night sky of the intro (0:17-0:25) has ~70 small grey dots of 10-80 % of the light of one pixel of
# ours; the 50 % threshold would lose them all. A star is a local maximum whose ring at distance 2 is dark (the
# glow around the moon at 1:40 is not) and whose 3x3 sum of grey over the ring's level is at least STAR_ON (the
# noise of the dark grey background at 1:39-1:48 is under 10); it becomes one white pixel. It twinkles: a star
# stays lit down to STAR_OFF when a pixel at most 1 away was lit in the picture before, so it does not blink at
# every frame. Elsewhere such dots are few (a glint, noise): a frame needs STAR_MIN of them. The particles around
# the tree (1:03-1:08) and the petals at 3:07 pass too.
STAR_ON, STAR_OFF = 40, 25
STAR_RING = 6
STAR_MIN = 5                  # fewer in a frame are rather glints in black figures or noise (1:55, 2:43)
STAR_CAND = re.compile(rb'[\x06-\x7f]')   # grey, not white: the candidates


def stars(f, prev=None):
    """Pixels (x, y) of the stars in grey frame f (bytes W*H); prev = rows of the picture before or None."""
    out = []
    for m in STAR_CAND.finditer(f, 2 * W, (H - 2) * W):
        p = m.start()
        y, x = divmod(p, W)
        if x < 2 or x >= W - 2:
            continue
        v = f[p]
        nb = (f[p - W - 1], f[p - W], f[p - W + 1], f[p - 1])
        if v <= max(nb) or v < max(f[p + 1], f[p + W - 1], f[p + W], f[p + W + 1]):
            continue
        ring = (f[p - 2 * W - 2:p - 2 * W + 3] + f[p + 2 * W - 2:p + 2 * W + 3] +
                bytes((f[p - W - 2], f[p - 2], f[p + W - 2], f[p - W + 2], f[p + 2], f[p + W + 2])))
        if max(ring) > STAR_RING:
            continue
        # the light of the dot over its background (the ring)
        s = sum(f[p - W - 1:p - W + 2]) + sum(f[p - 1:p + 2]) + sum(f[p + W - 1:p + W + 2]) - sum(ring) * 9 // 16
        if s >= STAR_ON or (s >= STAR_OFF and prev is not None and
                            any((prev[yy] >> (x - 1)) & 7 for yy in (y - 1, y, y + 1))):
            out.append((x, y))
    return out if len(out) >= STAR_MIN else []


# When the flight speeds up (0:21-0:22) the stars smear into horizontal streaks of ~10 x 2-3 pixels with grey up to
# 60; the dots above are not there. A streak is a patch of grey over STAR_RING, not touching white, 4 to STREAK_W
# wide and at most STREAK_H high, with light (grey over STAR_RING) of at least STAR_ON; it becomes a line 1 pixel
# high through the brightest pixel of each column that has at least STREAK_V.
STREAK_W, STREAK_H = 20, 4
STREAK_V = 15
STREAK_CAND = re.compile(rb'[\x07-\x7f]')


def streaks(f):
    """Lists of pixels (x, y) of the streaks in grey frame f (bytes W*H)."""
    seen = bytearray(W * H)
    out = []
    for m in STREAK_CAND.finditer(f):
        p0 = m.start()
        if seen[p0]:
            continue
        seen[p0] = 1
        stack, patch, ok = [p0], [], True
        while stack:
            p = stack.pop()
            patch.append(p)
            y, x = divmod(p, W)
            for q in (p - W - 1, p - W, p - W + 1, p - 1, p + 1, p + W - 1, p + W, p + W + 1):
                if 0 <= q < W * H and abs(q % W - x) <= 1 and not seen[q] and f[q] > STAR_RING:
                    if f[q] >= 128:
                        ok = False                  # the soft edge of a white shape
                        continue
                    seen[q] = 1
                    stack.append(q)
            if len(patch) > STREAK_W * STREAK_H:
                ok = False
        if not ok:
            continue
        xs = [p % W for p in patch]
        ys = [p // W for p in patch]
        if not 4 <= max(xs) - min(xs) + 1 <= STREAK_W or max(ys) - min(ys) + 1 > STREAK_H:
            continue
        if sum(f[p] - STAR_RING for p in patch) < STAR_ON:
            continue
        top = {}
        for p in patch:
            x = p % W
            if f[p] >= STREAK_V and (x not in top or f[p] > f[top[x]]):
                top[x] = p
        out.append([(p % W, p // W) for p in top.values()])
    return out


def picture(data, i, prev=None):
    """The 1-bit picture of source frame i: threshold 50 %, the stars and their streaks."""
    rows = rows_of(data, i)
    f = data[i * W * H:(i + 1) * W * H]
    lit = stars(f, prev)
    sk = streaks(f)
    if len(sk) >= STAR_MIN:
        lit += [px for s in sk for px in s]
    for x, y in lit:
        rows[y] |= 1 << x
    return rows


def runs(d):
    """Runs of ones in d: list of (s, e1) (e1 inclusive), ascending."""
    s = d & ~(d << 1)
    e = ~d & (d << 1)
    out = []
    while s:
        lo = s & -s
        a = lo.bit_length() - 1
        rest = e >> a
        out.append((a, a + (rest & -rest).bit_length() - 2))
        s ^= lo
    return out


def deadzone(d, dz, new):
    """Drop runs of at most dz pixels from the change d where an edge only jitters: the pixels left and right of
    the run differ and the run is one colour in the new row (the old row has the edge at its other end). A dot
    or a gap that comes or goes (both sides alike) stays, so does a run at the border of the picture."""
    if dz <= 0 or not d:
        return d
    for a, b in runs(d):
        if b - a < dz and a > 0 and b < W - 1:
            m = (1 << (b - a + 1)) - 1
            n = (new >> a) & m
            if ((new >> (a - 1)) ^ (new >> (b + 1))) & 1 and n in (0, m):
                d &= ~(m << a)
    return d


MEND_ROWS = 3


def mend(new, img):
    """Undo the dead zone where it leaves a notch. Rows are decided one by one, so a vertical edge that jitters
    would come out ragged. A notch is a run of at most MEND_ROWS pixels of one colour in a column between pixels
    of the other one, or a pixel whose left and right neighbours both have the other colour; its pixels and the
    pixels around it that are not as in img get as in img (either the stale run or the stale rows around a fresh
    one). Repeats while it changes something."""
    inner = (FULL >> 1) & ~1
    for _ in range(8):
        wrong = [a ^ b for a, b in zip(new, img)]
        fix = [((r ^ (r << 1)) & (r ^ (r >> 1)) & inner) & w for r, w in zip(new, wrong)]
        for k in range(1, MEND_ROWS + 1):
            for y0 in range(1, H - k):
                run = (new[y0 - 1] ^ new[y0]) & (new[y0 + k] ^ new[y0])
                for i in range(1, k):
                    run &= ~(new[y0 + i] ^ new[y0])
                if not run:
                    continue
                for y in range(y0 - 1, y0 + k + 1):
                    fix[y] |= run & wrong[y]
        if not any(fix):
            break
        new = [r ^ f for r, f in zip(new, fix)]
    return new


def row_addr(y):
    return (y + TOP) * vfmt.ROW + LEFT


# --- video memory rendering ------------------------------------------------------------------------------
REV4 = [int(f'{v:04b}'[::-1], 2) for v in range(16)]
NIB2BYTE = bytes(REV4[v] * 0x11 for v in range(16))


def render_row(r):
    """Picture row int -> 64 B of CGA mode."""
    return bytes(NIB2BYTE[(r >> (4 * j)) & 15] for j in range(64))


def render(rows):
    page = bytearray(PAGE)
    for y, r in enumerate(rows):
        a = row_addr(y)
        page[a:a + 64] = render_row(r)
    return page


# --- tracks ----------------------------------------------------------------------------------------------
def op_cost(code):
    t, r, w = mkvdec.costs()[code[0]]
    if vfmt.OPS[code[0]][0] == 'MX':
        m = vfmt.mx_m(code[1])
        t += m * mkvdec.MX_FILL[0] + mkvdec.MX_TAIL[0]
        r += m * mkvdec.MX_FILL[1] + mkvdec.MX_TAIL[1]
        w += m * mkvdec.MX_FILL[2] + mkvdec.MX_TAIL[2]
    return t + r * CGA_R + w * CGA_W


def nib(row, j):
    """Pixels of byte j of a row (4 bits, bit 0 = pixel 4j)."""
    return (row >> (4 * j)) & 15


def split_middles(ivs, old):
    """Intervals with 3 or more middle bytes are filled (MX): split those whose middle bytes are not all of one
    colour in the old row into pieces of at most 4 bytes (M codes, XOR)."""
    out = []
    for s, e1 in ivs:
        bs, be = s >> 2, e1 >> 2
        if be - bs - 1 >= 3:
            mids = {nib(old, j) for j in range(bs + 1, be)}
            if len(mids) > 1 or mids - {0, 15}:
                x = s
                while x <= e1:
                    end = min(e1, ((x >> 2) + 4) * 4 - 1)
                    out.append((x, end))
                    x = end + 1
                continue
        out.append((s, e1))
    return out


def build_tracks(ivrows):
    """ivrows: per row the list of (s, e1). Link intervals of consecutive rows whose left byte moves by at most
    one byte; returns a list of tracks, each (y0, [(s, e1), ...])."""
    tracks = []
    open_ = []                          # (left byte, track index) of the previous row
    for y in range(H):
        cur = []
        used = set()
        for s, e1 in ivrows[y]:
            bs = s >> 2
            best = None
            for k, (pbs, ti) in enumerate(open_):
                if k in used:
                    continue
                dd = abs(bs - pbs)
                if dd <= 1 and (best is None or dd < best[0]):
                    best = (dd, k)
                    if dd == 0:
                        break
            if best is None:
                tracks.append((y, [(s, e1)]))
                ti = len(tracks) - 1
            else:
                used.add(best[1])
                ti = open_[best[1]][1]
                tracks[ti][1].append((s, e1))
            cur.append((bs, ti))
        open_ = cur
    return tracks


T_CLR_OP = 222 + 10          # CLR: handler jump, parameters, DI, SP, dispatch
T_CLR_ROW = 413 + 64 * CGA_W  # per row: 32 x PUSH, EI window


def clr_cost(rows):
    return T_CLR_OP + rows * T_CLR_ROW


def encode_tracks(tracks, base, out, cyc=0):
    """Append the tracks and END to out; base = old rows (after clears) for the colour of MX; returns cycles."""
    tstart = None
    for y0, ivs in sorted(tracks, key=lambda t: row_addr(t[0]) + (t[1][0][0] >> 2)):
        de = 0xC000 + row_addr(y0) + (ivs[0][0] >> 2) - vfmt.ROW
        if tstart is not None and 0 <= de - tstart <= 255:
            code = bytes([vfmt.OP_TRACKR, de - tstart])
        else:
            code = bytes([vfmt.OP_TRACKA, de & 0xFF, de >> 8])
        tstart = de
        out += code
        cyc += op_cost(code)
        prev = ivs[0][0] >> 2
        for k, (s, e1) in enumerate(ivs):
            fill = 0xFF if nib(base[y0 + k], (s >> 2) + 1) == 0 else 0
            code = vfmt.code_for((s >> 2) - prev, s, e1, fill)
            prev = s >> 2
            out += code
            cyc += op_cost(code)
    out.append(vfmt.OP_END)
    cyc += op_cost(bytes([vfmt.OP_END]))
    return cyc


def iv_cost(ivs):
    """Rough cost of intervals (for choosing between XOR and clearing a row)."""
    c = 0
    for s, e1 in ivs:
        m = (e1 >> 2) - (s >> 2) - 1
        c += 95 if m < 0 else (135 + 28 * m if m < 3 else 200 + 16 * m)
    return c


# --- reference decoder (byte exact, like the Z80 code) ---------------------------------------------------
def decode_frame(buf, pos, page):
    """Apply the frame body at buf[pos:] to page (bytearray of 16 KB, offset 0 = C000h); returns the new pos."""
    de = 0
    tstart = 0
    while True:
        op = vfmt.OPS[buf[pos]]
        pos += 1
        k = op[0]
        if k == 'END':
            return pos
        if k == 'TRACKA':
            de = tstart = buf[pos] | buf[pos + 1] << 8
            pos += 2
            continue
        if k == 'TRACKR':
            de = tstart = (tstart + buf[pos]) & 0xFFFF
            pos += 1
            continue
        if k == 'CLR':
            a = (buf[pos] | buf[pos + 1] << 8) - 0xC000
            rows, col = buf[pos + 2], buf[pos + 3]
            pos += 4
            for r in range(rows):
                page[a + r * vfmt.ROW:a + r * vfmt.ROW + 64] = bytes([col]) * 64
            continue
        de = (de + vfmt.ROW + op[1]) & 0xFFFF
        a = de - 0xC000
        if k == 'S':
            page[a] ^= vfmt.pix_mask(op[2], op[3])
            continue
        page[a] ^= vfmt.pix_mask(op[2], 3)
        if k == 'M':
            m = op[4]
            for i in range(1, m + 1):
                page[a + i] ^= 0xFF
        else:
            m = vfmt.mx_m(buf[pos])
            col = 0xFF if buf[pos] & 1 else 0
            pos += 1
            page[a + 1:a + m + 1] = bytes([col]) * m
        page[a + m + 1] ^= vfmt.pix_mask(0, op[3])


# --- encoder ---------------------------------------------------------------------------------------------
def frame_body(page_rows, new_rows, use_clr=True):
    """Body of one frame: CLR of rows where clearing and drawing the new row is cheaper than XOR, tracks, END.
    Returns (bytes, cycles)."""
    ivrows = []
    base = []                                  # old rows after the clears
    clr = []                                   # per row: None or colour 0 / 1
    for y in range(H):
        iv = split_middles(runs(page_rows[y] ^ new_rows[y]), page_rows[y])
        best = (iv_cost(iv), None, iv, page_rows[y])
        if use_clr and best[0] > T_CLR_ROW:
            for col in (0, 1):
                b = FULL if col else 0
                iv2 = runs(new_rows[y] ^ b)
                c = T_CLR_ROW + 60 + iv_cost(iv2)
                if c < best[0]:
                    best = (c, col, iv2, b)
        clr.append(best[1])
        ivrows.append(best[2])
        base.append(best[3])
    out = bytearray()
    cyc = 0
    y = 0
    while y < H:
        if clr[y] is None:
            y += 1
            continue
        y1 = y
        while y1 + 1 < H and clr[y1 + 1] == clr[y]:
            y1 += 1
        a = 0xC000 + row_addr(y)
        out += bytes([vfmt.OP_CLR, a & 0xFF, a >> 8, y1 - y + 1, 0xFF if clr[y] else 0])
        cyc += clr_cost(y1 - y + 1)
        y = y1 + 1
    cyc = encode_tracks(build_tracks(ivrows), base, out, cyc)
    return out, cyc + len(out) * T_READ


def music_writes(path=MUSIC):
    """Register writes of the music per tick (empty without build/music.bin)."""
    if not os.path.exists(path):
        return []
    st = open(path, 'rb').read()
    p = 0
    while st[p] < 0xFE:
        p += 2
    out = []
    while st[p] != 0xFE:
        if st[p] == 0xFF:
            out.append(0)
            p += 1
        else:
            out[-1] += 1
            p += 2
    return out


MUSIC_WRITES = music_writes()


def free_t(v):
    """T of the decoder in VBI v (the interrupt and the music taken away)."""
    w = max(MUSIC_WRITES[max(0, v - 1):v + 2] or [0])
    return VBI_T - ISR_BASE_T - ISR_WRITE_T * w


def vbis_needed(cyc, start):
    """VBIs a frame of cyc T of the decoder takes from VBI start on (at least 2: 29.97 fps)."""
    need, have = 0, 0
    while have < cyc + FRAME_T or need < 2:
        have += free_t(start + need)
        need += 1
    return need


# Dead zones tried in turn until the frame makes it in 2 VBIs. The wide ones only in the heavy frames (a cut, fast
# motion): an edge lags there for a frame, but fewer frames are late and dropped.
DEADZONES = (1, 2, 3, 5, 8)


def shown_picture(shown, img, z):
    """What frame img will look like: the dead zone z against the picture shown, then mended."""
    return mend([shown[y] ^ deadzone(shown[y] ^ img[y], z, img[y]) for y in range(H)], img)


def encode(n_frames=None, check=False, verbose=True, observe=None):
    n_src, data = frames.load(W, H)
    t_end = (frames.SRC_FRAMES * 1001 // 1000) * 2      # VBIs of the whole video
    pages = [[0] * H, [0] * H]
    vram = [bytearray(PAGE), bytearray(PAGE)]
    shown = [0] * H
    prev_img = None
    stream = bytearray()
    stats = []
    flip = -2                     # VBI of the flip of the previous frame
    n = 0
    while True:
        target = flip + 2
        if target >= t_end or (n_frames and n >= n_frames):
            break
        page = pages[n & 1]
        src = min(frames.SRC_FRAMES - 1, round(target * 1001 / 2000))
        img = picture(data, src, prev_img)
        for z in DEADZONES:
            new = shown_picture(shown, img, z)
            body, cyc = frame_body(page, new)
            need = vbis_needed(cyc, flip)
            if need <= 2:
                break
        if need > 2:
            # too slow (a cut): show it later and take the source frame of that time
            target = flip + need
            src = min(frames.SRC_FRAMES - 1, round(target * 1001 / 2000))
            img = picture(data, src, prev_img)
            new = shown_picture(shown, img, z)
            body, cyc = frame_body(page, new)
            need = vbis_needed(cyc, flip)
            target = max(target, flip + need)
        if check:
            v = vram[n & 1]
            decode_frame(body, 0, v)
            assert v == render(new), f'frame {n}: decoder mismatch'
        stream += bytes([target - flip]) + body
        pages[n & 1] = new
        shown = new
        prev_img = img
        err = sum(bin(new[y] ^ img[y]).count('1') for y in range(H))
        stats.append((len(body) + 1, cyc, z, err, target - flip))
        if observe:
            observe(n, src, img, new)
        flip = target
        n += 1
        if verbose and n % 1000 == 0:
            print(f'  frame {n}: {len(stream)} B', flush=True)
    stream.append(0)
    return stream, stats


def report(stats):
    m = len(stats)

    def q(col):
        v = sorted(s[col] for s in stats)
        return (f'median {v[m // 2]:.0f} p90 {v[m * 9 // 10]:.0f} p99 {v[m * 99 // 100]:.0f} '
                f'max {v[-1]:.0f} mean {sum(v) / m:.0f}')
    print(f'frames {m}, total {sum(s[0] for s in stats) / 1e6:.3f} MB')
    print('  bytes/frame ', q(0))
    print('  T/frame     ', q(1))
    print('  wrong px    ', q(3))
    for z in DEADZONES:
        c = sum(1 for s in stats if s[2] == z)
        if c:
            print(f'    dz {z}: {c} frames ({100 * c / m:.1f} %)')
    for v in range(2, 16):
        c = sum(1 for s in stats if s[4] == v)
        if c:
            print(f'    {v} VBIs: {c} frames')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--frames', type=int)
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--out')
    a = ap.parse_args()
    stream, stats = encode(a.frames, a.check)
    report(stats)
    if a.out:
        os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
        open(a.out, 'wb').write(stream)
        print(f'{a.out}: {len(stream)} B')


if __name__ == '__main__':
    main()
